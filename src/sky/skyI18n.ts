const DICTS: Record<string, Dict> = { en, ru, ro };

/** Chapter II translator — falls back to the core dictionary. */
export function tc(key: string): string {
  const d = DICTS[getLang()] ?? en;
  return d[key] ?? en[key] ?? coreT(key);
}

/** Localised item name (Chapter II items first, then Chapter I). */
export function tcItem(id: string): string {
  const d = DICTS[getLang()] ?? en;
  return d["i_" + id] ?? en["i_" + id] ?? coreItem(id);
}

/** Localised item description, or undefined when the item has none. */
export function tcItemDesc(id: string): string | undefined {
  const d = DICTS[getLang()] ?? en;
  return d["d_" + id] ?? en["d_" + id] ?? coreItemDesc(id);
}

/** Quest title + objective for Chapter II index 0..10. */
export function tcQuest(index: number): { title: string; text: string } {
  if (index >= 11) return { title: tc("ch2_done_title"), text: tc("ch2_done_text") };
  return { title: tc(`k${index}t`), text: tc(`k${index}x`) };
}
